package com.raha.vpn

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith
import org.robolectric.RobolectricTestRunner
import org.robolectric.annotation.Config

@RunWith(RobolectricTestRunner::class)
@Config(sdk = [34])
class ConfigStoreValidationTest {
    private val validObfs4 =
        "obfs4 192.0.2.10:443 " + "a".repeat(40) + " cert=AQID iat-mode=0"

    @Test
    fun acceptsSupportedProxySchemes() {
        listOf(
            "vless://id@example.com:443",
            "vmess://eyJhZGQiOiJleGFtcGxlLmNvbSJ9",
            "trojan://password@example.com:443",
            "hysteria2://password@example.com:443"
        ).forEach { assertTrue("Expected supported scheme: $it", ConfigStore.isSupported(it)) }

        val key = "AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA="
        val wireGuardConfig = """
            [Interface]
            PrivateKey = $key
            Address = 10.66.0.2/32

            [Peer]
            PublicKey = $key
            Endpoint = wg.example.net:51820
            AllowedIPs = 0.0.0.0/0
        """.trimIndent()
        assertTrue("Expected standard WireGuard config to be supported", ConfigStore.isSupported(wireGuardConfig))
        assertFalse("Custom WireGuard share URIs are not supported", ConfigStore.isSupported("wireguard://private-key@example.com:51820"))
    }

    @Test
    fun rejectsUnknownAndMalformedSchemes() {
        assertFalse(ConfigStore.isSupported("ftp://example.com/file"))
        assertFalse(ConfigStore.isSupported("not-a-config"))
        assertFalse("Oversized configurations must be rejected", ConfigStore.isSupported("vless://" + "a".repeat(128 * 1024)))
        assertFalse(ConfigStore.isSupported("obfs4 not-a-valid-bridge"))
        assertFalse("Hysteria v1 is not implemented", ConfigStore.isSupported("hysteria://password@example.com:443"))
        assertFalse("AnyTLS is not implemented", ConfigStore.isSupported("anytls://password@example.com:443"))
        assertFalse("Standalone SOCKS links are not implemented", ConfigStore.isSupported("socks5://user:pass@example.com:1080"))
    }

    @Test
    fun acceptsValidObfs4BridgeAndBridgePrefix() {
        assertTrue(ConfigStore.isSupported(validObfs4))
        assertTrue(ConfigStore.isSupported("Bridge $validObfs4"))
        assertTrue(ConfigStore.isSupported("BRIDGE $validObfs4"))
        assertTrue(ConfigStore.isSupported("bridge $validObfs4"))
        assertTrue(ConfigStore.isSupported(validObfs4.replaceFirst("obfs4", "OBFS4")))
        assertTrue(ConfigStore.isSupported("Bridge " + validObfs4.replaceFirst("obfs4", "OBFS4")))
    }

    @Test
    fun canonicalizesBridgeAndObfs4KeywordsForTor() {
        val canonical = validObfs4
        assertTrue(ConfigStore.normalizeObfs4Bridge(canonical) == canonical)
        assertTrue(ConfigStore.normalizeObfs4Bridge("BRIDGE OBFS4 " + canonical.substringAfter("obfs4 ")) == canonical)
        assertTrue(ConfigStore.normalizeObfs4Bridge("Bridge " + canonical.replaceFirst("obfs4", "ObFs4")) == canonical)
    }

    @Test
    fun rejectsObfs4InvalidPortsAndFingerprints() {
        val invalidPort = validObfs4.replace(":443 ", ":70000 ")
        val shortFingerprint = validObfs4.replace("a".repeat(40), "a".repeat(39))
        assertFalse(ConfigStore.isSupported(invalidPort))
        assertFalse(ConfigStore.isSupported(shortFingerprint))
    }
    @Test
    fun prioritizesTorBridgesSoTheyAppearInVisibleSearchResults() {
        val proxyResults = (1..500).map { "vless://node$it@example.com:443" }
        val bridge = "obfs4 192.0.2.10:443 " + "a".repeat(40) + " cert=AQID iat-mode=0"
        val results = PublicConfigSearch.prioritizeResults(listOf(proxyResults, listOf(bridge)))

        assertEquals(bridge, results.first())
        assertTrue(results.take(25).contains(bridge))
        assertEquals(results.size, results.distinct().size)
    }

    @Test
    fun decodesBase64SubscriptionEvenWhenCommentContainsUrl() {
        val config = "vless://123e4567-e89b-12d3-a456-426614174000@example.com:443#node"
        val encoded = android.util.Base64.encodeToString(
            ("# source: https://example.org/feed\n" + config).toByteArray(),
            android.util.Base64.NO_WRAP
        )

        assertEquals(listOf(config), PublicConfigSearch.parseFeedPayload(encoded))
    }

    @Test
    fun parsesPlainSubscriptionRemovesCommentsAndDuplicates() {
        val config = "trojan://secret@example.org:443#edge"
        val payload = """
            # public feed
            $config
            $config
            // generated by https://example.org
            unsupported://example.org:443
        """.trimIndent()

        assertEquals(listOf(config), PublicConfigSearch.parseFeedPayload(payload))
    }

    @Test
    fun rejectsUnrelatedBase64AndKeepsBridgeFeedsSeparate() {
        val unrelated = android.util.Base64.encodeToString(
            "this is not a proxy subscription".toByteArray(),
            android.util.Base64.NO_WRAP
        )
        assertTrue(PublicConfigSearch.parseFeedPayload(unrelated).isEmpty())
        assertEquals(listOf(validObfs4), PublicConfigSearch.parseFeedPayload(validObfs4, bridgeFeed = true))
        assertTrue(PublicConfigSearch.parseFeedPayload(validObfs4).isEmpty())
    }
    @Test
    fun parsesUrlSafeUnpaddedBase64AndNormalizesBridgePrefix() {
        val config = "vless://123e4567-e89b-12d3-a456-426614174000@example.net:443"
        val encoded = android.util.Base64.encodeToString(
            config.toByteArray(),
            android.util.Base64.URL_SAFE or android.util.Base64.NO_WRAP or android.util.Base64.NO_PADDING
        )
        assertEquals(listOf(config), PublicConfigSearch.parseFeedPayload(encoded))

        assertEquals(
            listOf(validObfs4),
            PublicConfigSearch.parseFeedPayload("Bridge $validObfs4", bridgeFeed = true)
        )
    }

    @Test
    fun reportsDuplicatesUnsupportedAndMalformedRowsSeparately() {
        val valid = "trojan://secret@example.net:443"
        val oversized = "vless://" + "x".repeat(64 * 1024)
        val report = PublicConfigSearch.parseFeedPayloadWithReport(
            listOf(valid, valid, "unsupported://example.net:443", oversized).joinToString("\n")
        )

        assertEquals(listOf(valid), report.configs)
        assertEquals(1, report.accepted)
        assertEquals(1, report.duplicates)
        assertEquals(1, report.unsupported)
        assertEquals(1, report.malformed)
    }

    @Test
    fun rejectsSubscriptionPayloadLargerThanEightMib() {
        val oversizedPayload = "x".repeat(8 * 1024 * 1024 + 1)
        try {
            PublicConfigSearch.parseFeedPayload(oversizedPayload)
            throw AssertionError("Oversized subscription should be rejected")
        } catch (expected: IllegalArgumentException) {
            assertTrue(expected.message.orEmpty().contains("8 MiB"))
        }
    }


    @Test
    fun parsesCloudflareTraceExitAddress() {
        assertEquals("203.0.113.7", TunnelConnectivityProbe.parseTraceExitIp("fl=abc\nip=203.0.113.7\nts=123"))
        assertEquals("2001:db8::1", TunnelConnectivityProbe.parseTraceExitIp("ip=2001:db8::1\ncolo=FRA"))
    }

    @Test
    fun rejectsMissingOrMalformedTraceAddress() {
        assertEquals(null, TunnelConnectivityProbe.parseTraceExitIp("fl=abc\nts=123"))
        assertEquals(null, TunnelConnectivityProbe.parseTraceExitIp("ip=not-an-ip"))
        assertEquals(null, TunnelConnectivityProbe.parseTraceExitIp("ip=999.999.999.999"))
        assertEquals(null, TunnelConnectivityProbe.parseTraceExitIp("ip=192.168.001.1"))
        assertEquals(null, TunnelConnectivityProbe.parseTraceExitIp("ip=2001:::1"))
        assertEquals(null, TunnelConnectivityProbe.parseTraceExitIp("ip=" + "1".repeat(46)))
    }
}
